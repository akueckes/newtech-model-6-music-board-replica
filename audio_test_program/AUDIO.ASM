;
;	GETNUM - TAKES A STRING WITH ADDRESS IN D/E, MAX NUM DIGITS IN B,
;                RETURNS A 16-BIT NUMBER IN H/L, SETS CARRY IN CASE OF ERROR
;                INPUT STRING SHOULD BE NULL TERMINATED
;
GETNUM:	LDAX	D		;FIRST DIGIT
	INX	D		;NEXT CHARACTER IN BUFFER
	CPI	' '		;SKIP LEADING BLANKS
	JZ	GETNUM
	MVI	H,0		;CLEAR HL
	MVI	L,0
	CALL	HEXINT		;CONVERT DIGIT TO INTEGER
	RC			;RETURN WITH CARRY SET IF NO DIGIT
GN2:	PUSH	PSW		;SAVE RESULT
	MVI	C,4		;SHIFT HL LEFT 4X
GN3:	MOV	A,L
	ORA	A		;CLEAR CARRY
	RAL
	MOV	L,A
	MOV	A,H
	RAL
	MOV	H,A
	DCR	C
	JNZ	GN3
	POP	PSW		;RESTORE RESULT
	ORA	L		;STORE RESULT IN L
	MOV	L,A
	DCR	B
	JZ	GN4
	LDAX	D
	INX	D
	CALL	HEXINT
	JNC	GN2
GN4:	ORA	A		;DONE, CLEAR CARRY, RESULT IN HL
	RET
;
HEXINT:	;CONVERT HEX DIGIT TO INT,RETURN RESULT IN A,SETS CARRY IN CASE OF ERROR
	CPI	'0'
	JM	HERR
	CPI	':'
	JP	HLET
	SUI	30H
	JMP	HOK
HLET:	ANI	0DFH	;TO UPPER CASE
	CPI	'A'
	JM	HERR
	CPI	'G'
	JP	HERR
	SUI	37H
HOK:	ORA	A	;CLEAR CARRY FOR OK
	RET
HERR:	STC		;SET CARRY FOR ERROR
	RET
