;
; DIV16 - 16-BIT UNSIGNED DIVISION USING A BIT-BY-BIT SHIFT-AND-SUBTRACT ALGORITHM.
;
;         DIVIDENT IN BC, DIVISOR IN HL, RETURNS QUOTIENT IN HL AND REMAINDER IN DE
;	  CARRY SET ON RETURN IN CASE OF DIVISION BY ZERO
;
	;TEST FOR DIVISION BY ZERO
DIV16:	MOV	A,H
	ORA	L
	STC
	RZ
	;PEPARE FOR REVERSE POLARITY SUBTRACTION
	MOV	A,B
	CMA
	MOV	D,A
	MOV	A,C
	CMA
	MOV	E,A
	INX	B
        XRA	A
	STA	QUOT
	STA	QUOT+1
	JMP	DIV_1
	;FIRST PHASE: DOUBLING THE DIVISOR
DIV_0:	DAD	B
DIV_1:	INR	A
        PUSH	H
        DAD	H
        JC	DIV_2
	DAD	D
	JNC	DIV_0
	;SECOND PHASE: SUBTRACTING FROM THE DIVIDEND AND ACCUMULATING QUOTIENT BITS
