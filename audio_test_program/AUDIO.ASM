;	AUDIO TEST UTILITY V1.0
;
;	TEST S100 BASED AUDIO BOARDS - CURRENTLY SUPPORTED:
;
;       - CROMEMCO D+7A (INCLUDING JS-1 JOYSTICK)
;	- ADS NOISEMAKER (WITH AY-3-8910 PSG CHIP)
;	- NEWTECH MODEL 6 MUISC BOARD
;	- SOLID STATE MUSIC SB-1
;
;	(C) COPYRIGHT 2026 ANSGAR KUECKES
;
;	TEMPI		METRONOME
;
;	LARGO:		40-60 BPM
;	LARGHETTO:	60-66 BPM
;	ADAGIO:		66-76 BPM
;	ANDANTE:	76-108 BPM
;	MODERATO:	108-120 BPM
;	ALLEGRO:	120-168 BPM
;	PRESTO:		168-200 BPM
;	PRESTISSIMO:	>200 BPM
;
;	DYNAMICS
;
;	0: SILENCE
;	1: PIANISSISSIMO (PPP)
;	2: PIANISSIMO (PP)
;	3: PIANO (P)
;	4: MEZZO PIANO (MP)
;	5: MEZZO FORTE (MF)
;	6: FORTE (F)
;	7: FORTISSIMO (FF)
;	8: FORTISSIMISSIMO (FFF)
;
;
	ORG	100H
BDOS	EQU	0005H		;BDOS ENTRY POINT
CONS	EQU	1		;READ CONSOLE
TYPEF	EQU	2		;TYPE FUNCTION
DIO	EQU	6		;DIRECT CONSOLE I/O
PRINTF	EQU	9		;BUFFER PRINT ENTRY
READSTR	EQU	10		;BUFFERED CONSOLE INPUT
BRKF	EQU	11		;BREAK KEY FUNCTION (TRUE IF CHAR READY)
OPENF	EQU	15		;FILE OPEN
CLOSEF	EQU	16		;FILE OPEN
READF	EQU	20		;READ FUNCTION
WRITEF	EQU	21		;READ FUNCTION
MAKEF	EQU	22		;FILE CREATE
SIZEF	EQU	35		;FILE SIZE
;
FCB	EQU	5CH		;FILE CONTROL BLOCK ADDRESS
BUFF	EQU	80H		;INPUT DISK BUFFER ADDRESS
;
;    --- FILE CONTROL BLOCK DEFINITIONS ---
FCBDN	EQU	FCB+0		;DISK NAME
FCBFN	EQU	FCB+1		;FILE NAME
FCBFT	EQU	FCB+9		;DISK FILE TYPE (3 CHARACTERS)
FCBRL	EQU	FCB+12		;FILE'S CURRENT REEL NUMBER
FCBRC	EQU	FCB+15		;FILE'S RECORD COUNT (0 TO 128)
FCBCR	EQU	FCB+32		;CURRENT (NEXT) RECORD NUMBER (0 TO 127)
FCBRN	EQU	FCB+33		;FCB LENGTH
;
;    --- I/O DEFAULTS ---
DAZBAS	EQU	00EH		;DAZZLER I/O BASE ADDRESS
D7ABAS	EQU	018H		;D7A I/O BASE ADDRESS
MB1BAS	EQU	024H		;MUSIC BOARD 1 I/O BASE ADDRESS
MB2BAS	EQU	028H		;MUSIC BOARD 2 I/O BASE ADDRESS
NMBAS	EQU	0CCH		;NOISEMAKER I/O BASE ADDRESS
SB1BAS	EQU	0D3H		;SB-1 BOARD 1 MEMORY BASE ADDRESS (MSB) - DEFAULT=80H
SB2BAS	EQU	0D4H		;SB-1 BOARD 2 MEMORY BASE ADDRESS (MSB) - DEFAULT=81H
;
DAZFLG	EQU	DAZBAS
D7ACH1	EQU	D7ABAS+1
D7ACH2	EQU	D7ABAS+3
MBCH1	EQU	MB1BAS
MBCH2	EQU	MB2BAS
NM1REG	EQU	NMBAS
NM1DAT	EQU	NMBAS+1
NM2REG	EQU	NMBAS+2
NM2DAT	EQU	NMBAS+3
;
;    --- SPECIAL CHARACTERS ---
CR	EQU	0DH	;CARRIAGE RETURN
LF	EQU	0AH	;LINE FEED
;
;    --- SET UP STACK ---
	LXI	H,0
	DAD	SP
;	ENTRY STACK POINTER IN HL FROM THE CCP
	SHLD	OLDSP
;	SET SP TO LOCAL STACK AREA (RESTORED AT QUIT)
	LXI	SP,STKTOP
;	
;    --- STARTUP MESSAGE ---
	LXI	D,SIGNON
	MVI	C,PRINTF
	CALL	BDOS
	
;    --- DEFAULTS ---
	MVI	A,0		;CLEAR LEGATO FLAGS
	STA	LEGATO
	MVI	A,074H		;SET ~20 MS REST DURATION FOR ACCENT
	STA	ACCENT
	MVI	A,1		;DA+7 VS NOISEMAKER VS MUSIC BOARD VS SB-1
	STA	HARDW
	MVI	A,2
	STA	NPLAYR		;SET 2 PLAYERS/VOICES
	MVI	A,120
	STA	METRO		;USE 120 BEATS PER MINUTE
	MVI	A,1
	STA	NGEN		;ENABLE NOISE GENERATOR
	MVI	A,127
	STA	PITCHN		;USE HIGHEST PITCH AS DEFAULT FOR NOISE GENERATOR
	JMP	USRCLK		;SKIP AUTODETECT
;
;	;TRY TO DETERMINE CPU CLOCK VIA DAZZLER
	CALL	DETECT		;AUTODETECT
	JC	USRCLK
	LXI	D,FNDMSG	;OUTPUT RESULT
	MVI	C,PRINTF
	CALL	BDOS
	LDA	SYSCLK
	CALL	PNIB
	LXI	D,MHZMSG
	MVI	C,PRINTF
	CALL	BDOS
	JMP	TABLES
;
	;ASK USER FOR CPU CLOCK
USRCLK:	MVI	A,0
	STA	DAZZLR
	LXI	D,CLKMSG
	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,8		;INPUT SYSTEM CLOCK
	CALL	CINPUT
	CPI	0
	JZ	USRCLK		;REPEAT FOR ZERO INPUT
	MVI	B,1
	CALL	GETNUM
	MOV	A,L
	STA	SYSCLK
;
;    --- SETUP TABLES ---
TABLES:	CALL	MKWAVT		;COPY SINUS WAVEFORM INTO WAVE TABLE
	LXI	H,WAVET		;FILL WAVEFORM #15 WITH RANDOM NOISE
	MVI	A,15
	ADD	H
	MOV	H,A
	MVI	A,1
	STA	SEED
TAB2:	CALL	RND
	MOV	M,A
	INR	L
	JNZ	TAB2
;
	;INITIALIZE VOLUME & CURRENT WAVEFORMS FOR LEFT AND RIGHT CHANNELS
	MVI	A,7		;VOLUME 0-7
	STA	VOL1
	STA	VOL2
	DCR	A
	STA	WFORMA		;SELECT CHANNEL 1 VOLUME VIA WAVETABLE
	STA	WFORMB		;SELECT CHANNEL 2 VOLUME VIA WAVETABLE
	CALL	SPITCH		;SETUP PITCH TABLE
	CALL	SMETRO		;SETUP METRONOME TABLE
;
;    --- MAIN MENU ---
	CALL	CRLF
	CALL	PRHW
MENU:	; PRINT THE MENUE
	LXI	D,USAGE1
	MVI	C,PRINTF
	CALL	BDOS
	LXI	D,USAGE2
	MVI	C,PRINTF
	CALL	BDOS
	LXI	D,USAGE3
	MVI	C,PRINTF
	CALL	BDOS
	LXI	D,USAGE4
	MVI	C,PRINTF
	CALL	BDOS
PROMPT:	CALL	CRLF
	MVI	A,'-'		;OUTPUT PROMPT
	CALL	PCHAR
	MVI	A,' '
	CALL	PCHAR
	MVI	C,CONS		;ENTER USER INPUT
	CALL	BDOS
	ANI	0DFH		;NORMALIZE TO UPPERCASE
	CPI	'H'
	JNZ	MENU1
	JMP	SELHW		;SELECT HARDWARE
MENU1:	CPI	'T'
	JNZ	MENU2
	JMP	PLAYT		;PLAY A TONE
MENU2:	CPI	'N'
	JNZ	MENU3
	JMP	PLAYN		;PLAY NOISE
MENU3:	CPI	'F'
	JNZ	MENU4
	JMP	PSMPLF		;PLAY SAMPLE FILE
MENU4:	CPI	'S'
	JNZ	MENU5
	JMP	PSCORF		;PLAY SCORE FILE
MENU5:	CPI	'W'
	JNZ	MENU6
	JMP	WAVTBL		;LOAD WAVETABLE FILE
MENU6:	CPI	'A'
	JNZ	MENU7
	JMP	TEST		;RUN AUDIO TEST
MENU7:	CPI	'J'
	JNZ	MENU8
	JMP	JOYSTK		;RUN JOYSTICK TEST
MENU8:	CPI	'Q'
	JNZ	MENU
QUIT:	;QUIT PROGRAM
	MVI	A,0		;DISABLE DAZZLER (IF NOT ALREADY DONE)
	OUT	0EH
	LHLD	OLDSP		;RESTORE CCP STACK POINTER
	SPHL
	RET			;RETURN TO CCP
;
;    --- MENUE FUNCTIONS ---
;
SELHW:	;SELECT HARDWARE
	LXI	D,HWMSG
	MVI	C,PRINTF
	CALL	BDOS
	LXI	D,NOISEM
	MVI	C,PRINTF
	CALL	BDOS
	LXI	D,D7A
	MVI	C,PRINTF
	CALL	BDOS
	LXI	D,MB
	MVI	C,PRINTF
	CALL	BDOS
	LXI	D,SB1
	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,'-'		;OUTPUT PROMPT
	CALL	PCHAR
	MVI	A,' '
	CALL	PCHAR
	MVI	C,CONS		;ENTER USER INPUT
	CALL	BDOS
	ORA	A		;CLEAR CARRY
	SBI	'0'
	STA	HARDW		;0=ADS NOISEMAKER, 1=CROMEMCO D+7A, 2=NEWTECH MUSIC BOARD 3=SSM SB-1
	CPI	3
	JNZ	SH3
	CALL	SBINIT		;INITIALIZE SB-1
	JMP	SH5
SH3:	CPI	0
	JNZ	SH4
	CALL	NINIT		;INITIALIZE NOISEMAKER
	JMP	SH5
SH4:	CALL    INIT		;INITIALIZE CROMEMCO D+7A / NEWTECH MUSIC MAKER
SH5:	CALL	SPITCH		;UPDATE PITCH TABLE
	CALL	SMETRO		;UPDATE METRONOME TABLE
	CALL	MKWAVT		;RE-CREATE WAVETABLE
	CALL	PRHW		;PRINT NEW HARDWARE SETTING
	JMP	PROMPT
;
PLAYT:	;PLAY TONE WITH VOLUME, DURATION & PITCH
	CALL	GETVOL		;PROMPT FOR VOLUME
	JC	PROMPT
	CALL	GETDUR		;PROMPT FOR DURATION
	JC	PROMPT
PT0:	LXI	D,PITMSG	;PROMPT FOR 16-BIT PITCH
	LDA	HARDW
	CPI	0
	JNZ	PT1
	LXI	D,PI2MSG	;PROMPT FOR 12-BIT PITCH
PT1:	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,8		;INPUT PITCH
	CALL	CINPUT
	CPI	0
	JZ	PROMPT
	MVI	B,3		;UP TO 3 DIGITS FOR NOISEMAKER
	LDA	HARDW
	CPI	0
	JZ	PT2
	MVI	B,4		;UP TO 4 DIGITS FOR ALL OTHERS
PT2:	CALL	GETNUM
	JC	PROMPT
	MOV	A,L
	STA	PITCHA
	STA	PITCHB
	MOV	A,H
	STA	PITCHA+1
	STA	PITCHB+1
	CALL	PTONE
	JMP	PT0
;
PLAYN:	;PLAY NOISE
	LDA	HARDW
	CPI	3		;SB-1 LACKS NOISE GENERATOR
	JNZ	PLN0
	LXI	D,NONOIS
	MVI	C,PRINTF
	CALL	BDOS
	JMP	PROMPT	
PLN0:	CALL	GETVOL		;PROMPT FOR VOLUME
	JC	PROMPT
	CALL	GETDUR		;PROMPT FOR DURATION
	JC	PROMPT
PLN1:	LXI	D,PINMSG	;PROMPT FOR PITCH
	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,8		;INPUT NOISE PITCH (0=LOWEST, FF=HIGHEST)
	CALL	CINPUT
	CPI	0
	JZ	PROMPT
	MVI	B,2		;UP TO 2 DIGITS
	CALL	GETNUM
	JC	PROMPT
	MOV	A,L
	ANI	07FH
	STA	PITCHN
	CALL	PNOISE
	JMP	PLN1
;
PSMPLF:	;PLAY STEREO 8-BIT SAMPLES FROM FILE (2 SIGNED BYTES/16 BITS PER STEREO SAMPLE)
	CALL	FOPEN
	JNC	PROMPT		;QUIT ON ERROR
	CALL	CRLF
	LXI	D,FCB		;GET FILE SIZE
	MVI	C,SIZEF
	CALL	BDOS
	LXI	H,STKTOP	;READ THE FILE INTO MEMORY
	CALL	FREAD
	JNC	PROMPT		;QUIT ON ERROR
	CALL	FCLOSE		;CLOSE FILE
	LXI	D,SPDMSG	;PROMPT FOR SPEED
	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,8		;INPUT SPEED
	CALL	CINPUT
	CPI	0
	JZ	PROMPT
	MVI	B,2		;UP TO 2 DIGITS
	CALL	GETNUM
	MOV	H,L		;STORE SPEED IN H
	ORA	A		;STORE SAMPLE COUNT IN B/C
	LDA	FCBRC		;NUMBER OF 128 BYTE RECORDS
	RAR
	MOV	B,A
	MVI	A,0
	RAR
	MOV	C,A
	LXI	D,STKTOP	;STORE ADDRESS OF SAMPLES IN D/E
	CALL	PSAMPL		;PLAY SAMPLES
	JMP	PROMPT
;
PSCORF:	;PLAY SCORE FROM FILE
	CALL	FOPEN
	JNC	PROMPT		;QUIT ON ERROR
	CALL	CRLF
	LXI	H,STKTOP	;READ THE FILE INTO MEMORY
	CALL	FREAD
	JNC	PROMPT		;QUIT ON ERROR
	CALL	FCLOSE		;CLOSE FILE
	LXI	D,STKTOP
	CALL	PSCORE
	JMP	PROMPT
;
WAVTBL:	;LOAD WAVE TABLE FROM FILE
	CALL	FOPEN		;LOAD MASTER
	JNC	PROMPT		;QUIT ON ERROR
	CALL	CRLF
	LXI	H,SIN256	;READ THE FILE INTO WAVETABLE MASTER
	CALL	FREAD
	JNC	PROMPT		;QUIT ON ERROR
	CALL	FCLOSE		;CLOSE FILE
	CALL	MKWAVT		;RE-CREATE WAVE TABLE 
	JMP	PROMPT
;
TEST:	;RUN AUDIO TEST
	;PART I: SLIDING TONES (LEFT/RIGHT TEST)
	LXI	D,TMSG1
	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,4		;HALF VOLUME
	STA	VOL1
	STA	VOL2
	MVI	A,2		;DURATION
	STA	DURAT+1
	MVI	A,0
	STA	DURAT
	STA	PITCHA
	STA	PITCHA+1
	STA	PITCHB
	LDA	HARDW
	CPI	0		;NOISEMAKER?
	JZ	TST11
	CPI	3		;SB-1?
	JZ	TST11
	JMP	TST0
TST11:	MVI	A,8		;NOISEMAKER OR SB-1
	STA	PITCHB+1
	MVI	A,0
TST6:	PUSH	A		;LOOP COUNTER
	LDA	PITCHA
	ADI	02H
	STA	PITCHA
	LDA	PITCHA+1
	ACI	0
	STA	PITCHA+1
	LDA	PITCHB
	SUI	02H
	STA	PITCHB
	LDA	PITCHB+1
	SBI	0
	STA	PITCHB+1
	CALL	PTONE
	POP	A
	INR	A
	JP	TST6
	JMP	TST7
TST0:	PUSH	A		;ALL OTHERS
	STA	PITCHA+1
	MOV	B,A
	MVI	A,127
	SUB	B
	STA	PITCHB+1
	CALL	PTONE
	POP	A
	INR	A
	JP	TST0
; PART II: STEREO POSITIONING TEST
TST7:	LXI	D,TMSG2
	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,16		;DURATION
	STA	DURAT+1
	LDA	HARDW
	CPI	0
	JNZ	TST8
	MVI	A,2		;NOISEMAKER PITCH MSB
	JMP	TST9
TST8:	CPI	3
	JNZ	TST12
	MVI	A,4		;SB-1 OCTAVE
	JMP	TST9
TST12:	MVI	A,8		;DAC PITCH
TST9:	STA	PITCHA+1
	STA	PITCHB+1
	MVI	A,0
	STA	PITCHA
	STA	PITCHB
	MVI	A,1		;START VOLUME
	MVI	B,1		;START DIRECTION
TST1:	PUSH	A
	PUSH	B
	STA	VOL1
	DCR	A
	STA	WFORMA
	MOV	B,A
	MVI	A,7
	SUB	B
	STA	VOL2
	DCR	A
	STA	WFORMB
	CALL	PTONE
	POP	B
	POP	A
	ADD	B
	CPI	0
	JZ	TST2
	CPI	7
	JC	TST1
	MVI	B,-1		;TURN BACK
	JMP	TST1
; PART III: WHITE NOISE TEST
TST2:	LDA	HARDW
	CPI	3		;SB-1 LACKS NOISE GENERATOR
	JZ	TST10
	LXI	D,TMSG3
	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,16		;DURATION
	STA	DURAT+1
	MVI	A,07FH
	STA	PITCHN
	MVI	A,1		;START VOLUME
	MVI	B,1		;DIRECTION
TST3:	PUSH	A		;TEST NOISE VOLUME
	PUSH	B
	STA	VOL1
	STA	VOL2
	CALL	PNOISE
	POP	B
	POP	A
	ADD	B
	CPI	0
	JZ	TST4
	CPI	7
	JC	TST3
	MVI	B,-1		;TURN BACK
	JMP	TST3
TST4:	MVI	A,4		;TEST NOISE PITCH
	STA	VOL1
	STA	VOL2
	LXI	H,500
	SHLD	DURAT		;DURATION
	MVI	A,07FH
TST5:	STA	PITCHN
	CALL	PNOISE
	LDA	PITCHN
	DCR	A
	JNZ	TST5
	MVI	A,1
; PART VI: PLAY SCORE
TST10:	LXI	D,TMSG4
	MVI	C,PRINTF
	CALL	BDOS
	LXI	D,SCORE		;POINTER TO SCORE TABLE
	CALL	PSCORE
	JMP	PROMPT
;
JOYSTK:	; JOYSTICK / GAME CONTROLLER TEST
	CALL	BREAK
	RRC
	JC	PROMPT
	IN	24		;BUTTONS JOYSTICKS 1 & 2
	CALL	PHEX
	MVI	A,','
	CALL	PCHAR
	IN	25		;X-AXIS JOYSTICK 1
	CALL	PHEX
	MVI	A,','
	CALL	PCHAR
	IN	26		;Y-AXIS JOYSTICK 1
	CALL	PHEX
	MVI	A,','
	CALL	PCHAR
	IN	27		;X-AXIS JOYSTICK 2
	CALL	PHEX
	MVI	A,','
	CALL	PCHAR
	IN	28		;Y-AXIS JOYSTICK 2
	CALL	PHEX
	CALL	CRLF
	JMP	JOYSTK
;
PRHW:	;PRINT CURRENT HARDWARE
	LDA	HARDW
	CPI	0
	JNZ	PRHW1
	LXI	D,NMKMSG	;NOISEMAKER
	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,NMBAS
	CALL	PHEX
	MVI	A,'H'
	CALL	PCHAR
	CALL	CRLF
	RET
PRHW1:	CPI	1
	JNZ	PRHW2
	LXI	D,D7AMSG	;D+7A
	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,D7ABAS
	CALL	PHEX
	MVI	A,'H'
	CALL	PCHAR
	CALL	CRLF
	RET
PRHW2:	CPI	2
	JNZ	PRHW3
	LXI	D,MBMSG
	MVI	C,PRINTF	;MUSIC BOARD
	CALL	BDOS
	MVI	A,MB1BAS
	CALL	PHEX
	MVI	A,'H'
	CALL	PCHAR
	MVI	A,'+'
	CALL	PCHAR
	MVI	A,MB2BAS
	CALL	PHEX
	MVI	A,'H'
	CALL	PCHAR
	CALL	CRLF
	RET
PRHW3:	CPI	3
	RNZ
	LXI	D,SB1MSG
	MVI	C,PRINTF	;SB-1
	CALL	BDOS
	MVI	A,SB1BAS
	CALL	PHEX
	MVI	A,0
	CALL	PHEX	
	MVI	A,'H'
	CALL	PCHAR
	MVI	A,'+'
	CALL	PCHAR
	MVI	A,SB2BAS
	CALL	PHEX
	MVI	A,0
	CALL	PHEX	
	MVI	A,'H'
	CALL	PCHAR
	CALL	CRLF
	RET
;
GETVOL:	LXI	D,VOLMSG	;PROMPT FOR VOLUME
	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,8		;INPUT VOLUME
	CALL	CINPUT
	CPI	0		;TERMINATE ON SILENCE
	STC
	RZ
	MVI	B,1		;UP TO 1 DIGIT
	CALL	GETNUM
	RC
	MOV	A,L
	STA	VOL1
	STA	VOL2
	DCR	A
	STA	WFORMA		;ADJUST WAVETABLE BY VOLUME
	STA	WFORMB
	RET
;
GETDUR:	LXI	D,DURMSG	;PROMPT FOR DURATION
	MVI	C,PRINTF
	CALL	BDOS
	MVI	A,8		;INPUT DURATION
	CALL	CINPUT
	CPI	0
	STC
	RZ
	MVI	B,2		;UP TO 2 DIGITS
	CALL	GETNUM
	RC
	MVI	A,0
	STA	DURAT
	MOV	A,L
	STA	DURAT+1
	RET
;
;
;    --- HARDWARE INDEPENDENT AUDIO ROUTINES ---
;
;	PSCORE - PLAY SCORE FROM SCORE TABLE WITH ADDRESS IN D/E
;
;	SCORE TABLE - ACTUAL MUSIC SCORE (THREE BYTES PER EVENT)
;
;	RESTRICTIONS:
;	- 2 CHANNELS WITH ONE VOICE PER CHANNEL
;	- 7 VOLUME LEVELS PLUS SILENCE (VOLUMES IMPLEMENTED WITH WAVEFORMS FOR BETTER PERFORMANCE)
;	- NO ENVELOPES YET (NOISEMAKER & SB-1 ARE ALWAYS USING FLAT ENVELOPES)
;	- NO CONCURRENT PLAYBACK OF MUSIC + WHITE NOISE
;
PSCORE:	LDAX	D		;GET 1ST BYTE FROM SCORE TABLE (COMMAND + PARAMETER)
	ANI	0FH		;GET PARAMETER INTO B
	MOV	B,A
	LDAX	D		;GET COMMAND
	RRC
	RRC
	RRC
	RRC
	ANI	07H
	CPI	0		;TERMINATE COMMAND
	JNZ	PS15
	LDA	HARDW
	CPI	0
	RNZ			;NO ACTION FOR DAC'S
	MVI	A,7		;DISABLE LEFT CHANNEL
	OUT	NM1REG
	MVI	A,0FFH
	OUT	NM1DAT
	MVI	A,7		;DISABLE RIGHT CHANNEL
	OUT	NM2REG
	MVI	A,0FFH
	OUT	NM2DAT	
	RET
PS15:	CPI	1		;MUSIC/NOISE EVENT
	JZ	EVENT	
	CPI	2		;VOLUME COMMAND
	JNZ	PS9
	MOV	A,B
	CPI	8		;WE SUPPORT ONLY 7 LEVELS PLUS SILENCE
	JC	PS11
	MVI	A,7		;MAX VOLUME
PS11:	STA	VOL1		;TODO: VOLUME FOR EACH VOICE
	STA	VOL2
	DCR	A		;WAVETABLE INDEX = VOLUME-1
	MOV	B,A
	JMP	PS12
PS9:	CPI	3		;WAVEFORM COMMAND?
	JNZ	PS4
PS12:	LDAX	D
	ANI	080H		;APPLY TO ALL VOICES?
	JZ	PS7
	INX	D		;GET VOICE SELECTION FROM COMPLEMENTARY BYTE
	LDAX	D
	CPI	0
	JNZ	PS6
	MOV	A,B		;VOICE 0 / CHANNEL A
	STA	WFORMA
	JMP	PSDONE
PS6:	MOV	A,B		;VOICE 1 / CHANNEL B
	STA	WFORMB
	JMP	PSDONE
PS7:	MOV	A,B		;APPLY TO ALL VOICES/CHANNELS
	STA	WFORMA
	STA	WFORMB
	JMP	PSDONE
PS4:	CPI	4		;ENVELOPE COMMAND (NOT YET IMPLEMENTED)
	JNZ	PS5
	MOV	A,B
	STA	ENVEL
	JMP	PSDONE
PS5:	CPI	5		;NUMBER VOICES COMMAND (NOT YET IMPLEMENTED)
