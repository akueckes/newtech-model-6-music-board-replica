	ANI	040H
	JZ	AD1
	;WAIT FOR END OF FRAME
	LXI	B,0B000H	;TIMEOUT VALUE
AD2:	DCX	B
	MOV	A,B
	ORA	C
	JZ	TIMOUT		;BREAK ON TIMEOUT
	IN	DAZFLG
	ANI	040H
	JNZ	AD2
	;WAIT FOR END OF VERTICAL BLANK (4 MS)
	LXI	B,0A0H		;TIMEOUT VALUE
	LXI	D,0
AD3:	MVI	A,08H		;LATENCY LOOP
AD4:	DCR	A
	JNZ	AD4
	INX	D		;LOOP COUNT
	DCX	B
	MOV	A,B
	ORA	C
	JZ	TIMOUT		;BREAK ON TIMEOUT
	IN	DAZFLG
	ANI	040H
	JZ	AD3
	MVI	A,1		;YES WE HAVE DAZZLER!
	STA	DAZZLR
	;AUTODETECT CPU CLOCK FROM B/C 2MHZ=46, 4MH=90, 6MHZ=136
