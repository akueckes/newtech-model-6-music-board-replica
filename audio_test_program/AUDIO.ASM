;	SMETRO - SET METRONOME/TEMPO IN BEATS PER MINUTE
;
;	REMARK: TEMPI < 95 BPM MAY NOT FIT ANY MORE INTO 16-BIT LOOP COUNTS
;               FOR LONG NOTES ON FAST 6 MHZ CPUS
;
;	TONE DURATIONS FOR 120 BPM WITH RESPECT TO 62 HZ DAZZLER FIELD FREQUENCY:
;
;	 1 FULL NOTE WITH DOT		192 VIDEO FIELDS
;	 2 FULL NOTE 			128 VIDEO FIELDS
;	 3 HALF NOTE WITH DOT 		 96 VIDEO FIELDS
;	 4 HALF NOTE 			 64 VIDEO FIELDS
;	 5 QUARTER NOTE WITH DOT	 48 VIDEO FIELDS
;	 6 QUARTER NOTE			 32 VIDEO FIELDS
;	 7 EIGHTH NOTE WIDTH DOT	 24 VIDEO FIELDS
;        8 1/3 HALF NOTE                 21 VIDEO FIELDS
;	 9 EIGHTH NOTE			 16 VIDEO FIELDS
;	10 SIXTEENTH NOTE WITH DOT 	 12 VIDEO FIELDS
;	11 1/3 QUARTER NOTE              11 VIDEO FIELDS
;	12 SIXTEENTH NOTE		  8 VIDEO FIELDS
;	13 THIRTY-SECOND NOTE WITH DOT	  6 VIDEO FIELDS
;	14 THIRTY-SECOND NOTE		  4 VIDEO FIELDS
;	15 1/3 EIGTH NOTE                 3 VIDEO FIELDS
;
;	DURATION (LOOP COUNT) OF QUARTER NOTE = 
;		= (SYSCLK * 1,000,000) * (60 / BPM) / CLOCKCYCLES
;		= 178,042 * SYSCLK / BPM (FOR 337 CLOCKCYCLES)
;
;      = 17804 / BPM * 10 * SYSCLK
;
SMETRO:	;CREATE DURATION TABLES FOR 2MHZ, 4MHZ AND 6MHZ CPU CLOCKS (DEPENDING ON METRO AND SYSCLK)
	;STEP 1: CALCULATE LOOP COUNT FOR QUARTER NOTE
	LXI	B,17804		;DIVIDE 17804 BY BPM
	MVI	H,0
	LDA	METRO
	MOV	L,A
	CALL	DIV16		;NOW QUOTIENT IS IN HL WITH REMAINDER IN DE
	XCHG			;MOVE QUOTIENT TO DE
	LXI	H,0		;TIMES 10
	MVI	A,10
MET0:	DAD	D
	DCR	A
	JNZ	MET0
	XCHG
	LXI	H,0		;TIMES SYSCLK
	LDA	SYSCLK
MET1::	DAD	D
	DCR	A
	JNZ	MET1
	;STEP 2: CREATE DURATION TABLE
	SHLD	DURATT+12	;QUARTER NOTE
	CALL	MULT2
	SHLD	DURATT+8	;HALF NOTE
	CALL	MULT2
	SHLD	DURATT+4	;FULL NOTE
	LHLD	DURATT+12	;EIGTH NOTE
	CALL	DIV2
	SHLD	DURATT+18
	CALL	DIV2		;SIXTEENTH NOTE
	SHLD	DURATT+24
	CALL	DIV2		;THIRTY-SECOND NOTE
	SHLD	DURATT+30
	LHLD	DURATT+4	;FULL NOTE WITH DOT
	XCHG
	LHLD	DURATT+8
	DAD	D
	SHLD	DURATT+2
	LHLD	DURATT+8	;HALF NOTE WITH DOT
	XCHG
	LHLD	DURATT+12
	DAD	D
	SHLD	DURATT+6	
	LHLD	DURATT+12	;QUARTER NOTE WITH DOT
	XCHG
	LHLD	DURATT+18
	DAD	D
	SHLD	DURATT+10	
	LHLD	DURATT+18	;EIGTH NOTE WITH DOT
	XCHG
	LHLD	DURATT+24
	DAD	D
	SHLD	DURATT+14	
	LHLD	DURATT+24	;SIXTEENTH NOTE WITH DOT
	XCHG
	LHLD	DURATT+28
	DAD	D
	SHLD	DURATT+20	
	LHLD	DURATT+28	;THIRTY-SECOND NOTE WITH DOT
	CALL	DIV2
	XCHG
	LHLD	DURATT+28
	DAD	D
	SHLD	DURATT+26
	LHLD	DURATT+8	;1/3 HALF NOTE
	MOV	B,H
	MOV	C,L	
	LXI	H,3
	CALL	DIV16
	SHLD	DURATT+16
	LHLD	DURATT+12	;1/3 QUARTER NOTE
	MOV	B,H
	MOV	C,L	
	LXI	H,3
	CALL	DIV16
	SHLD	DURATT+22
	LHLD	DURATT+18	;1/3 EIGTH NOTE
	MOV	B,H
	MOV	C,L	
	LXI	H,3
	CALL	DIV16
	SHLD	DURATT+28
	LXI	H,0		;RESERVED
	SHLD	DURATT
	RET
