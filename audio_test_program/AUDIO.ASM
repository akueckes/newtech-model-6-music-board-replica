DIV_3:	POP	H
	DAD	D
	JC	DIV_4
	XCHG
DIV_4:	CMC
	LDA	QUOT
	RAL
	STA	QUOT
	LDA	QUOT+1
	RAL
	STA	QUOT+1
	DCR	B
	JNZ	DIV_3
	LHLD	QUOT
	MOV	A,E
	CMA
	MOV	E,A
	MOV	A,D
	CMA
	MOV	D,A
	RET
